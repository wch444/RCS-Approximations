function models = validate_unified_fit( ...
        fit,dataset_name,market,trial,data_train,data_test)
%VALIDATE_UNIFIED_FIT Validate one canonical fitted-parameter artifact.

schema = unified_fit_schema();
config = dataset_config(dataset_name);
dataset_name = char(config.name);
market = char(string(market));
if strcmp(dataset_name,'expedia')
    expected_fields = schema.expedia_fields;
    expected_lambda_length = 4;
else
    expected_fields = schema.trivago_fields;
    expected_lambda_length = 3;
end
if ~isstruct(fit) || ~isscalar(fit) ...
        || ~isequal(sort(fieldnames(fit)),sort(expected_fields(:))) ...
        || fit.schema_version ~= schema.version ...
        || ~strcmp(fit.artifact_type,schema.artifact_type) ...
        || ~strcmp(fit.dataset,dataset_name) ...
        || ~strcmp(fit.market,market) || fit.trial ~= trial ...
        || ~strcmp(fit.rng,'twister') ...
        || ~strcmp(fit.mmnl_seed_rule,'legacy_paper_mmnl_v1') ...
        || ~strcmp(fit.scm_parameter_order,schema.scm_parameter_order) ...
        || fit.feature_start ~= config.feature_start ...
        || fit.feature_end ~= config.feature_end ...
        || fit.data_schema_version ~= config.data_schema_version ...
        || fit.page_size ~= 10 ...
        || fit.mmnl_components ~= schema.mmnl_components ...
        || fit.mmnl_estimator_version ~= schema.mmnl_estimator_version
    error('validate_unified_fit:InvalidSchema', ...
        'Fit metadata do not satisfy the unified artifact schema.');
end

canonical_index = find(config.markets == string(market),1);
if isempty(canonical_index)
    error('validate_unified_fit:InvalidTask','Unknown market %s.',market);
end
expected_mmnl_seed = paper_mmnl_seed(dataset_name,market,trial);
if strcmp(dataset_name,'trivago')
    expected_seed = 42+1000*trial+canonical_index;
else
    expected_seed = expected_mmnl_seed;
end
data_name = sprintf(config.data_pattern,market,trial);
expected_data_file = fullfile('data','processed',dataset_name,data_name);
if fit.seed ~= expected_seed || fit.mmnl_seed ~= expected_mmnl_seed ...
        || ~strcmp(fit.data_file,expected_data_file)
    error('validate_unified_fit:InvalidTask', ...
        'Fit task identity or fixed seed is not canonical.');
end

validate_matrix_reference(data_test,'test');
matrix_columns = size(data_test,2);
if matrix_columns < config.feature_end ...
        || fit.matrix_columns ~= matrix_columns ...
        || (~isempty(config.matrix_columns) ...
            && matrix_columns ~= config.matrix_columns) ...
        || fit.test_rows ~= size(data_test,1) ...
        || fit.test_sessions ~= numel(unique(data_test(:,1)))
    error('validate_unified_fit:InvalidData', ...
        'Fit test dimensions do not match the requested matrix.');
end
if isempty(data_train)
    valid_train = is_positive_integer(fit.train_rows) ...
        && is_positive_integer(fit.train_sessions) ...
        && fit.train_sessions <= fit.train_rows;
else
    validate_matrix_reference(data_train,'train');
    valid_train = size(data_train,2) == matrix_columns ...
        && fit.train_rows == size(data_train,1) ...
        && fit.train_sessions == numel(unique(data_train(:,1)));
end
if ~valid_train
    error('validate_unified_fit:InvalidData', ...
        'Fit training dimensions do not match the requested matrix.');
end

if ~isstruct(fit.models) || ~isscalar(fit.models) ...
        || ~isequal(sort(fieldnames(fit.models)), ...
            sort(schema.model_fields(:)))
    error('validate_unified_fit:InvalidModels', ...
        'fit.models does not contain the exact canonical model fields.');
end
models = fit.models;
n_short = config.feature_end-config.feature_start+1;
n_full = matrix_columns-config.feature_start+1;
vector_lengths = struct('scm',2*n_short,'mnl',n_full, ...
    'cmnl',2*n_full,'seqinv',n_short,'nsmnl',n_short, ...
    'nsmnl_lambda',expected_lambda_length);
names = fieldnames(vector_lengths);
for index = 1:numel(names)
    name = names{index};
    value = models.(name);
    if ~isnumeric(value) || ~isreal(value) || ~isvector(value) ...
            || numel(value) ~= vector_lengths.(name) ...
            || any(~isfinite(value),'all')
        error('validate_unified_fit:InvalidModels', ...
            'Model field %s has an invalid dimension or value.',name);
    end
    models.(name) = value(:);
end
alpha = models.mmnl_alpha;
beta = models.mmnl_beta;
if ~isnumeric(alpha) || ~isreal(alpha) || ~isvector(alpha) ...
        || numel(alpha) ~= schema.mmnl_components ...
        || any(~isfinite(alpha),'all') || any(alpha < 0) ...
        || abs(sum(alpha)-1) > 1e-10 ...
        || ~isnumeric(beta) || ~isreal(beta) ...
        || ~isequal(size(beta),[n_full,schema.mmnl_components]) ...
        || any(~isfinite(beta),'all')
    error('validate_unified_fit:InvalidModels', ...
        'MMNL parameters have invalid dimensions, values, or weights.');
end
models.mmnl_alpha = alpha(:).';
lambda = models.nsmnl_lambda;
if any(lambda < 0) || abs(sum(lambda)-1) > 1e-8
    error('validate_unified_fit:InvalidModels', ...
        'NSMNL lambda must be a nonnegative probability vector.');
end
end


function validate_matrix_reference(data,label)
if ~isnumeric(data) || ~ismatrix(data) || isempty(data) ...
        || any(~isfinite(data),'all') || any(diff(data(:,1)) < 0)
    error('validate_unified_fit:InvalidData', ...
        '%s data must be a finite matrix sorted by session.',label);
end
end


function valid = is_positive_integer(value)
valid = isnumeric(value) && isreal(value) && isscalar(value) ...
    && isfinite(value) && value == fix(value) && value > 0;
end
