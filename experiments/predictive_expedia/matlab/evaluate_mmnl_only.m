function [results, means] = evaluate_mmnl_only(dataset_name, markets, trials)
%EVALUATE_MMNL_ONLY Evaluate MMNL from unified Expedia fit artifacts.
%   The direct API validates the current archive grid and requires every fit
%   to match the identified Expedia
%   parameterization and its fixed paper seed.  Full default evaluations
%   publish 50 trial rows and five market means.  Subset calls return tables
%   without replacing publication files.

here = fileparts(mfilename('fullpath'));
root = fileparts(fileparts(fileparts(here)));
addpath(fullfile(root,'common','matlab','models'),'-begin');
addpath(fullfile(root,'common','matlab','workflow'),'-begin');
addpath(fullfile(root,'common','matlab','publishing'),'-begin');
if nargin < 1 || isempty(dataset_name), dataset_name = "expedia"; end
require_expedia(dataset_name);
config = dataset_config("expedia");
if nargin < 2 || isempty(markets), markets = config.markets; end
if nargin < 3 || isempty(trials), trials = 1:10; end
markets = string(markets);
if ~isvector(markets) || isempty(markets) || any(ismissing(markets)) ...
        || any(strlength(markets) == 0)
    error('evaluate_mmnl_only:InvalidMarkets', ...
        'Markets must be a nonempty nonmissing vector.');
end
markets = markets(:).';
canonical_market_indices(markets, config); % Validate membership/uniqueness.
trials = validate_trials(trials);

data_dir = fullfile(root, 'data', 'processed', char(config.name));
fit_dir = fullfile(root,'opt_data',char(config.name));
output_dir = fullfile(fileparts(here), 'results');
full_grid = is_full_grid(markets,trials,config);
preflight_files(data_dir, fit_dir, config, markets, trials, full_grid);

em_options = struct('MaxIterations', 100, 'RelativeTolerance', 1e-7);
n_row = numel(markets) * numel(trials);
market_col = strings(n_row, 1);
trial_col = zeros(n_row, 1);
model_col = repmat("MMNL", n_row, 1);
metric = nan(n_row, 7);
converged_col = false(n_row, 1);
cap_col = false(n_row, 1);
reason_col = strings(n_row, 1);
iteration_col = zeros(n_row, 1);
row = 0;

for trial = trials
    for market = markets
        data_name = sprintf(config.data_pattern, char(market), trial);
        data_file = fullfile(data_dir, data_name);
        fit_file = fullfile(fit_dir, ...
            sprintf('fit_%s_%d.mat',char(market),trial));
        data = load(data_file, 'data_train', 'data_test');
        if ~all(isfield(data, {'data_train','data_test'}))
            error('evaluate_mmnl_only:InvalidData', ...
                'Archived MAT must contain data_train and data_test.');
        end
        validate_matrix(data.data_train,config,'train');
        validate_matrix(data.data_test,config,'test');
        if size(data.data_train,2) ~= size(data.data_test,2)
            error('evaluate_mmnl_only:InvalidData', ...
                'Archived training and test matrices must have the same width.');
        end
        artifact = load(fit_file, 'fit');
        [fit,models] = validate_fit(artifact,config,market,trial, ...
            data.data_train,data.data_test,em_options);

        [~, ~, nll, hit, rmse, weighted, mape] = ...
            Mix_MNL_EM_function(models.mmnl_alpha,models.mmnl_beta, ...
                config.feature_start, [], data.data_test, [], true, ...
                em_options);
        values = [nll, rmse, weighted, mape, hit(:).'];
        if numel(values) ~= 7 || any(~isfinite(values)) ...
                || any(values(1:4) < 0) ...
                || any(values(5:7) < 0 | values(5:7) > 1) ...
                || any(diff(values(5:7)) < -1e-12)
            error('evaluate_mmnl_only:NonFiniteMetric', ...
                'MMNL returned an invalid metric for %s trial %d.', ...
                market, trial);
        end

        row = row + 1;
        market_col(row) = market;
        trial_col(row) = trial;
        metric(row, :) = values;
        converged_col(row) = fit.mmnl_diagnostics.converged;
        cap_col(row) = fit.mmnl_diagnostics.hit_iteration_cap;
        reason_col(row) = string(fit.mmnl_diagnostics.termination_reason);
        iteration_col(row) = fit.mmnl_diagnostics.iterations_accepted;
    end
end

results = table(market_col, trial_col, model_col, metric(:, 1), ...
    metric(:, 2), metric(:, 3), metric(:, 4), metric(:, 5), ...
    metric(:, 6), metric(:, 7), converged_col, cap_col, reason_col, ...
    iteration_col, ...
    'VariableNames', {'Market', 'Trial', 'Model', 'NLL', ...
    'RMSE', 'WeightedSquaredError', 'MAPE', 'Hit1', 'Hit2', 'Hit3', ...
    'Converged', 'HitIterationCap', 'TerminationReason', ...
    'IterationsAccepted'});
means = aggregate_means(results, markets, trials);

prepublish_validator = @() validate_prepublish_inputs( ...
    data_dir,fit_dir,config,markets,trials);
write_mmnl_evaluation_bundle(results,means,output_dir,markets,trials, ...
    config.markets,prepublish_validator);
end


function [fit,models] = validate_fit( ...
        artifact,config,market,trial,data_train,data_test,em_options)
if ~isstruct(artifact) || ~isscalar(artifact) ...
        || ~isfield(artifact, 'fit') || ~isstruct(artifact.fit) ...
        || ~isscalar(artifact.fit)
    error('evaluate_mmnl_only:InvalidFit', ...
        'Artifact must contain one scalar fit structure.');
end
fit = artifact.fit;
models = fit.models;
matrix_columns = size(data_test,2);
expected_seed = paper_mmnl_seed(config.name, market, trial);
n_feature = matrix_columns-config.feature_start+1;
valid_initialization = isnumeric(fit.mmnl_beta0_full) ...
    && isreal(fit.mmnl_beta0_full) ...
    && isequal(size(fit.mmnl_beta0_full),[n_feature,3]) ...
    && all(isfinite(fit.mmnl_beta0_full),'all');
if ~valid_initialization
    error('evaluate_mmnl_only:InvalidFit', ...
        'MMNL-only full initialization is malformed.');
end
previous_rng = rng;
rng_cleanup = onCleanup(@() rng(previous_rng));
rng(expected_seed,'twister');
expected_beta0_full = rand(n_feature,3);
clear rng_cleanup
if ~isequal(fit.mmnl_beta0_full,expected_beta0_full)
    error('evaluate_mmnl_only:InvalidFit', ...
        'MMNL-only full initialization does not match its paper seed.');
end
[train_reduced,~,expected_beta0_reduced,parameterization] = ...
    expedia_mmnl_identifiable_parameterization( ...
        data_train,data_test,expected_beta0_full,config.feature_start);
valid_parameterization = ...
    strcmp(fit.parameterization,parameterization.parameterization) ...
    && fit.reference_bin == parameterization.reference_bin ...
    && fit.reference_feature_index ...
        == parameterization.reference_feature_index ...
    && same_numeric_row(fit.position_feature_indices, ...
        parameterization.position_feature_indices) ...
    && same_numeric_row(fit.constrained_zero_bins, ...
        parameterization.constrained_zero_bins) ...
    && same_numeric_row(fit.constrained_zero_feature_indices, ...
        parameterization.constrained_zero_feature_indices) ...
    && same_numeric_row(fit.reduced_feature_indices, ...
        parameterization.reduced_feature_indices) ...
    && fit.full_feature_dimension ...
        == parameterization.full_feature_dimension ...
    && fit.reduced_feature_dimension ...
        == parameterization.reduced_feature_dimension ...
    && fit.full_train_rank == parameterization.full_train_rank ...
    && fit.train_rank == parameterization.train_rank ...
    && isnumeric(fit.mmnl_beta0_reduced) ...
    && isreal(fit.mmnl_beta0_reduced) ...
    && isequal(fit.mmnl_beta0_reduced,expected_beta0_reduced);
if ~valid_parameterization
    error('evaluate_mmnl_only:InvalidFit', ...
        ['MMNL-only parameterization metadata or reduced initialization ' ...
         'does not match the fitted training design.']);
end

diagnostics = fit.mmnl_diagnostics;
valid_diagnostic_metadata = isfield(diagnostics,'component_order') ...
    && same_numeric_row(sort(diagnostics.component_order),1:3) ...
    && numel(unique(diagnostics.component_order)) == 3 ...
    && isfield(diagnostics,'em_options') ...
    && isequal(diagnostics.em_options,em_options);
if ~valid_diagnostic_metadata
    error('evaluate_mmnl_only:InvalidFit', ...
        'MMNL diagnostic metadata do not match the evaluation contract.');
end

valid_parameters = isnumeric(fit.mmnl_beta_reduced) ...
    && isreal(fit.mmnl_beta_reduced) ...
    && isequal(size(fit.mmnl_beta_reduced), ...
        [parameterization.reduced_feature_dimension,3]) ...
    && all(isfinite(fit.mmnl_beta_reduced),'all') ...
    && isequal(models.mmnl_beta(parameterization.reduced_feature_indices,:), ...
        fit.mmnl_beta_reduced) ...
    && all(models.mmnl_beta([parameterization.reference_feature_index, ...
        parameterization.constrained_zero_feature_indices],:) == 0,'all');
if ~valid_parameters
    error('evaluate_mmnl_only:InvalidFit', ...
        'MMNL-only parameters are nonfinite, malformed, or outside the simplex.');
end
validate_train_nll_endpoints( ...
    fit,models,train_reduced,config.feature_start,em_options);
end


function validate_train_nll_endpoints( ...
        fit,models,train_reduced,feature_start,em_options)
alpha0 = ones(1,3)/3;
[~,~,initial_nll] = Mix_MNL_EM_function( ...
    alpha0,fit.mmnl_beta0_reduced,feature_start,[],train_reduced,[],true, ...
    em_options);
[~,~,final_nll] = Mix_MNL_EM_function( ...
    models.mmnl_alpha,fit.mmnl_beta_reduced,feature_start,[],train_reduced, ...
    [],true,em_options);
diagnostics = fit.mmnl_diagnostics;
tolerance = 1e-10*(1+max(abs([initial_nll,final_nll])));
if ~isfinite(initial_nll) || ~isfinite(final_nll) ...
        || abs(initial_nll-diagnostics.initial_train_nll) > tolerance ...
        || abs(final_nll-diagnostics.final_train_nll) > tolerance
    error('evaluate_mmnl_only:InvalidFit', ...
        ['MMNL diagnostic NLL endpoints do not match independent ' ...
         'reevaluation of the saved initialization and final parameters.']);
end
end


function same = same_numeric_row(first,second)
same = isnumeric(first) && isreal(first) ...
    && all(isfinite(first),'all') ...
    && isequal(double(first(:).'),double(second(:).'));
end


function require_expedia(dataset_name)
valid_text = (ischar(dataset_name) && isrow(dataset_name)) ...
    || (isstring(dataset_name) && isscalar(dataset_name) ...
        && ~ismissing(dataset_name));
if ~valid_text || ~strcmp(char(dataset_name), 'expedia')
    error('evaluate_mmnl_only:UnsupportedDataset', ...
        'The MMNL-only evaluation workflow supports only Expedia.');
end
end



function [markets, trials, filenames] = expected_archive_grid(config)
n_task = numel(config.markets) * 10;
markets = strings(n_task,1);
trials = zeros(n_task,1);
filenames = strings(n_task,1);
row = 0;
for market = config.markets
    for trial = 1:10
        row = row + 1;
        markets(row) = market;
        trials(row) = trial;
        filenames(row) = sprintf(config.data_pattern, char(market), trial);
    end
end
end



function means = aggregate_means(results, markets, trials)
n_market = numel(markets);
market_col = markets(:);
model_col = repmat("MMNL", n_market, 1);
metric = nan(n_market, 7);
n_tasks = zeros(n_market, 1);
converged_tasks = zeros(n_market, 1);
capped_tasks = zeros(n_market, 1);
for market_index = 1:n_market
    use = results.Market == markets(market_index);
    if sum(use) ~= numel(trials)
        error('evaluate_mmnl_only:IncompleteOutput', ...
            'Each requested market must contain every requested trial.');
    end
    metric(market_index, :) = mean(results{use, 4:10}, 1);
    n_tasks(market_index) = sum(use);
    converged_tasks(market_index) = sum(results.Converged(use));
    capped_tasks(market_index) = sum(results.HitIterationCap(use));
end
means = table(market_col, model_col, metric(:, 1), metric(:, 2), ...
    metric(:, 3), metric(:, 4), metric(:, 5), metric(:, 6), ...
    metric(:, 7), n_tasks, converged_tasks, capped_tasks, ...
    'VariableNames', {'Market', 'Model', 'NLL', 'RMSE', ...
    'WeightedSquaredError', 'MAPE', 'Hit1', 'Hit2', 'Hit3', ...
    'NTasks', 'ConvergedTasks', 'CappedTasks'});
end


function trials = validate_trials(trials)
if ~isnumeric(trials) || ~isvector(trials) || isempty(trials) ...
        || ~isreal(trials) ...
        || any(~isfinite(trials)) || any(trials ~= fix(trials)) ...
        || any(trials < 1 | trials > 10) ...
        || numel(unique(trials)) ~= numel(trials)
    error('evaluate_mmnl_only:InvalidTrials', ...
        'Trials must be unique integers from 1 through 10.');
end
trials = double(trials(:).');
end


function preflight_files(data_dir,fit_dir,config,markets,trials,full_grid)
for trial = trials
    for market = markets
        data_name = sprintf(config.data_pattern, char(market), trial);
        require_file(fullfile(data_dir, data_name));
        require_file(fullfile(fit_dir, ...
            sprintf('fit_%s_%d.mat',char(market),trial)));
    end
end
if full_grid
    data_entries = dir(fullfile(data_dir,'*.mat'));
    observed_data = sort(string({data_entries.name}).');
    [~,~,expected_data] = expected_archive_grid(config);
    entries = dir(fullfile(fit_dir,'*.mat'));
    observed = sort(string({entries.name}).');
    expected = strings(50,1);
    row = 0;
    for market = config.markets
        for trial = 1:10
            row = row + 1;
            expected(row) = sprintf('fit_%s_%d.mat',char(market),trial);
        end
    end
    if numel(observed_data) ~= 50 ...
            || ~isequal(observed_data,sort(expected_data))
        error('evaluate_mmnl_only:InvalidDataGrid', ...
            'A full evaluation requires the exact canonical 50-data MAT grid.');
    end
    if numel(observed) ~= 50 || ~isequal(observed,sort(expected))
        error('evaluate_mmnl_only:InvalidFitGrid', ...
            'A full evaluation requires the exact canonical 50-fit MAT grid.');
    end
end
end


function require_file(path)
if ~isfile(path)
    error('evaluate_mmnl_only:MissingFile', ...
        'Missing required matrix or unified fit: %s',path);
end
end


function validate_matrix(data,config,split)
split = validatestring(char(split),{'train','test'});
if ~isnumeric(data) || ~ismatrix(data) || isempty(data) ...
        || size(data, 2) < config.feature_end ...
        || any(~isfinite(data), 'all') || any(diff(data(:, 1)) < 0) ...
        || any(data(:,1) ~= fix(data(:,1)))
    error('evaluate_mmnl_only:InvalidData', ...
        'data_%s must be a finite nonempty matrix sorted by session.',split);
end
if ~isempty(config.matrix_columns) ...
        && size(data, 2) ~= config.matrix_columns
    error('evaluate_mmnl_only:InvalidData', ...
        'data_%s does not match the configured matrix width.',split);
end
session_ids = data(:,1);
starts = [1; find(session_ids(2:end) ~= session_ids(1:end-1))+1];
ends = [starts(2:end)-1; size(data,1)];
if any(~ismember(data(:,5),[0,1])) ...
        || any(splitapply(@sum,data(:,5),findgroups(session_ids)) ~= 1) ...
        || any(data(ends,2) ~= 0) || any(data(ends,4) ~= 100) ...
        || any(data(ends,7) ~= 0)
    error('evaluate_mmnl_only:InvalidData', ...
        ['data_%s violates the session, choice, or trailing-outside ' ...
         'contract.'],split);
end
end


function full_grid = is_full_grid(markets, trials, config)
full_grid = numel(markets) == numel(config.markets) ...
    && all(ismember(config.markets, markets)) ...
    && isequal(sort(trials), 1:10);
end



function validate_prepublish_inputs(data_dir,fit_dir,config,markets,trials)
preflight_files(data_dir,fit_dir,config,markets,trials,true);
end
