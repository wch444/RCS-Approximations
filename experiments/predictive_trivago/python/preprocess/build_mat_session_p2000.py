#!/usr/bin/env python3
"""Merge Trivago features and build deterministic price-capped MATLAB samples."""

from __future__ import annotations

import argparse
import json
import random
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.io import savemat


PLATFORMS = ("BR", "US", "JP", "UK", "DE")
PLATFORM_ID = {platform: index + 1 for index, platform in enumerate(PLATFORMS)}
TRIALS = tuple(range(1, 11))
FEATURES = [
    "log_price",
    "star_rating",
    "rating_tier",
    "is_luxury",
    "is_business",
    "has_pool",
    "has_gym",
    "has_spa",
    "is_mobile",
    "is_tablet",
]
ITEM_FEATURES = [
    "star_rating",
    "rating_tier",
    "is_luxury",
    "is_business",
    "has_pool",
    "has_gym",
    "has_spa",
]
N_SAMPLE = 10_000
TRAIN_FRACTION = 0.60
MIN_CLICKOUT_ALTERNATIVES = 5
POSITION_BIN_COUNT = 5
MAT_HEADER = b"MATLAB 5.0 MAT-file, generated by the SCM reproducibility pipeline"


def stabilize_mat_header(path: Path) -> None:
    """Remove SciPy's wall-clock timestamp from a generated MATLAB v5 file."""

    header = MAT_HEADER[:116].ljust(116, b" ")
    with path.open("r+b") as handle:
        handle.write(header)


def fit_scaler(frame: pd.DataFrame) -> dict[str, dict[str, float]]:
    """Fit population-variance standardization statistics for one split."""

    scaler: dict[str, dict[str, float]] = {}
    for column in FEATURES:
        # Several metadata indicators arrive from Parquet as float32.  Cast
        # before reduction so the recorded population moments and resulting
        # z-scores are not affected by float32 accumulation error.
        values = frame[column].to_numpy(dtype=np.float64, copy=False)
        mean = float(np.mean(values, dtype=np.float64))
        std = float(np.std(values, ddof=0, dtype=np.float64))
        if not np.isfinite(mean) or not np.isfinite(std) or std == 0:
            raise ValueError(f"Cannot standardize constant/invalid column {column!r}.")
        scaler[column] = {"mean": mean, "std": std}
    return scaler


def apply_scaler(
    frame: pd.DataFrame, scaler: dict[str, dict[str, float]]
) -> pd.DataFrame:
    """Apply an explicitly recorded split-specific scaler."""

    result = frame.copy()
    if set(scaler) != set(FEATURES):
        raise ValueError("Scaler columns do not match the Trivago feature contract.")
    for column in FEATURES:
        mean = scaler[column]["mean"]
        std = scaler[column]["std"]
        if not np.isfinite(mean) or not np.isfinite(std) or std == 0:
            raise ValueError(f"Invalid scaler statistics for {column!r}.")
        values = result[column].to_numpy(dtype=np.float64, copy=False)
        result[column] = (values - mean) / std
    return result


def add_outside(frame: pd.DataFrame, columns: list[str]) -> pd.DataFrame:
    ids = frame["srch_id"].drop_duplicates().to_numpy()
    outside = pd.DataFrame(0.0, index=range(len(ids)), columns=columns)
    outside["srch_id"] = ids
    outside["position"] = 100
    booked = frame.groupby("srch_id")["booking_bool"].sum()
    if ((booked < 0) | (booked > 1)).any():
        raise ValueError("Each retained Trivago session must contain at most one choice.")
    outside["booking_bool"] = (
        outside["srch_id"].map(booked).fillna(0).to_numpy() < 1
    ).astype(float)
    result = pd.concat([frame[columns], outside], ignore_index=True)
    return result.sort_values(["srch_id", "position"], kind="mergesort").reset_index(
        drop=True
    )


def split(frame: pd.DataFrame, seed: int) -> tuple[pd.DataFrame, pd.DataFrame]:
    ids = list(frame["srch_id"].unique())
    random.Random(seed).shuffle(ids)
    ids = ids[: min(N_SAMPLE, len(ids))]
    cut = round(len(ids) * TRAIN_FRACTION)
    train_ids, test_ids = set(ids[:cut]), set(ids[cut:])
    return (
        frame.loc[frame["srch_id"].isin(train_ids)].copy(),
        frame.loc[frame["srch_id"].isin(test_ids)].copy(),
    )


def filter_valid_sessions(
    long: pd.DataFrame, features: pd.DataFrame, price_cap: float
) -> tuple[pd.DataFrame, dict[str, int]]:
    """Apply row filters without ever converting a click-out to no-choice.

    A click-out session is discarded in full when its chosen hotel fails the
    metadata or price filter.  After invalid non-chosen rows are removed, a
    click-out session must still contain at least the five alternatives
    required by the upstream construction; a no-clickout proxy session must
    remain nonempty.
    """

    required_long = {
        "srch_id",
        "prop_id",
        "position",
        "booking_bool",
        "click_bool",
        "origin_price",
        "device",
        "is_abandoned",
    }
    required_features = {"item_id", *ITEM_FEATURES}
    missing_long = sorted(required_long.difference(long.columns))
    missing_features = sorted(required_features.difference(features.columns))
    if missing_long or missing_features:
        raise ValueError(
            f"Missing Trivago columns: long={missing_long}, features={missing_features}."
        )
    if long.empty:
        raise ValueError("No Trivago session rows were provided.")
    if features["item_id"].duplicated().any():
        raise ValueError("Trivago item features contain duplicate item_id values.")

    session = long.groupby("srch_id", sort=False).agg(
        is_abandoned=("is_abandoned", "first"),
        abandoned_values=("is_abandoned", "nunique"),
        choice_count=("booking_bool", "sum"),
        n_rows=("srch_id", "size"),
    )
    if (session["abandoned_values"] != 1).any():
        raise ValueError("is_abandoned must be constant within each Trivago session.")
    abandoned = session["is_abandoned"].astype(bool)
    invalid_outcome = (abandoned & (session["choice_count"] != 0)) | (
        ~abandoned & (session["choice_count"] != 1)
    )
    if invalid_outcome.any():
        raise ValueError(
            "Each click-out session must have exactly one chosen row and each "
            "no-clickout session must have none."
        )

    frame = long.merge(
        features[["item_id", *ITEM_FEATURES]],
        left_on="prop_id",
        right_on="item_id",
        how="left",
        validate="many_to_one",
        indicator="_metadata_merge",
    )
    item_values = frame[ITEM_FEATURES].to_numpy(dtype=np.float64)
    invalid_metadata = (frame["_metadata_merge"] != "both").to_numpy() | ~np.isfinite(
        item_values
    ).all(axis=1)
    price = frame["origin_price"].to_numpy(dtype=np.float64)
    price_nonfinite = ~np.isfinite(price)
    price_negative = price < 0
    price_above_cap = price > price_cap
    invalid_price = price_nonfinite | price_negative | price_above_cap
    invalid_row = invalid_metadata | invalid_price
    chosen = frame["booking_bool"].to_numpy() == 1

    chosen_invalid_metadata_ids = set(
        frame.loc[chosen & invalid_metadata, "srch_id"].tolist()
    )
    chosen_invalid_price_ids = set(frame.loc[chosen & invalid_price, "srch_id"].tolist())
    chosen_invalid_ids = chosen_invalid_metadata_ids | chosen_invalid_price_ids

    eligible_mask = ~frame["srch_id"].isin(chosen_invalid_ids).to_numpy()
    eligible = frame.loc[eligible_mask].copy()
    eligible_session_ids = set(eligible["srch_id"].unique().tolist())
    filtered = frame.loc[eligible_mask & ~invalid_row].copy()

    remaining_size = filtered.groupby("srch_id", sort=False).size()
    remaining_ids = set(remaining_size.index.tolist())
    empty_ids = eligible_session_ids.difference(remaining_ids)
    clickout_ids = set(session.index[~abandoned].tolist()).difference(chosen_invalid_ids)
    below_minimum_ids = {
        session_id
        for session_id in clickout_ids
        if 0 < int(remaining_size.get(session_id, 0)) < MIN_CLICKOUT_ALTERNATIVES
    }
    dropped_after_row_filter = empty_ids | below_minimum_ids
    filtered = filtered.loc[~filtered["srch_id"].isin(dropped_after_row_filter)].copy()

    final = filtered.groupby("srch_id", sort=False).agg(
        is_abandoned=("is_abandoned", "first"),
        choice_count=("booking_bool", "sum"),
        n_rows=("srch_id", "size"),
    )
    final_abandoned = final["is_abandoned"].astype(bool)
    if (
        (final["n_rows"] < 1).any()
        or ((~final_abandoned) & (final["n_rows"] < MIN_CLICKOUT_ALTERNATIVES)).any()
        or (final_abandoned & (final["choice_count"] != 0)).any()
        or ((~final_abandoned) & (final["choice_count"] != 1)).any()
    ):
        raise AssertionError("Post-filter Trivago session invariants failed.")

    diagnostics = {
        "input_sessions": int(len(session)),
        "input_clickout_sessions": int((~abandoned).sum()),
        "input_no_clickout_sessions": int(abandoned.sum()),
        "input_rows": int(len(frame)),
        "rows_missing_or_invalid_metadata": int(invalid_metadata.sum()),
        "rows_with_nonfinite_price": int(price_nonfinite.sum()),
        "rows_with_negative_price": int(price_negative.sum()),
        "rows_above_price_cap": int(price_above_cap.sum()),
        "dropped_clickout_sessions_chosen_invalid_metadata": len(
            chosen_invalid_metadata_ids
        ),
        "dropped_clickout_sessions_chosen_invalid_price": len(chosen_invalid_price_ids),
        "dropped_clickout_sessions_chosen_invalid_total": len(chosen_invalid_ids),
        "dropped_sessions_empty_after_row_filter": len(empty_ids),
        "dropped_clickout_sessions_below_minimum_after_row_filter": len(
            below_minimum_ids
        ),
        "retained_sessions": int(len(final)),
        "retained_clickout_sessions": int((~final_abandoned).sum()),
        "retained_no_clickout_sessions": int(final_abandoned.sum()),
        "retained_rows": int(len(filtered)),
    }
    return filtered.drop(columns=["item_id", "_metadata_merge"]), diagnostics


def make_position_dummies(position: pd.Series) -> pd.DataFrame:
    """Create the five position-group indicators used in the manuscript run."""

    page = np.floor(position.to_numpy(dtype=np.float64) / 5).astype(int)
    if ((page < 0) | (page >= POSITION_BIN_COUNT)).any():
        raise ValueError(
            "Trivago positions must fall in the five declared bins (0 through 24)."
        )
    page_type = pd.Categorical(page, categories=range(POSITION_BIN_COUNT))
    dummies = pd.get_dummies(
        page_type, prefix="position_bin", prefix_sep="_", dtype=float
    )
    dummies.index = position.index
    return dummies


def prepare_platform(
    prep_dir: Path, platform: str, price_cap: float
) -> tuple[pd.DataFrame, list[str], dict[str, int]]:
    long = pd.read_parquet(prep_dir / f"queries_long_session_{platform}.parquet")
    features = pd.read_parquet(prep_dir / "item_features.parquet")
    frame, diagnostics = filter_valid_sessions(long, features, price_cap)
    frame["log_price"] = np.log1p(frame["origin_price"].astype(np.float64))
    frame["is_mobile"] = (frame["device"] == "mobile").astype(np.float32)
    frame["is_tablet"] = (frame["device"] == "tablet").astype(np.float32)
    frame = frame.sort_values(["srch_id", "position"], kind="mergesort")
    frame["position"] = frame.groupby("srch_id").cumcount()
    frame["site_id"] = PLATFORM_ID[platform]
    frame["b_0"] = 1.0

    dummies = make_position_dummies(frame["position"])
    base = [
        "srch_id",
        "prop_id",
        "site_id",
        "position",
        "booking_bool",
        "click_bool",
        "origin_price",
        "b_0",
        *FEATURES,
    ]
    frame = pd.concat([frame[base], dummies], axis=1)
    return frame, list(frame.columns), diagnostics


def build(prep_dir: Path, output_dir: Path, price_cap: float) -> None:
    output_dir.mkdir(parents=True, exist_ok=True)
    manifest: dict[str, object] = {
        "schema_version": 2,
        "platforms": list(PLATFORMS),
        "price_cap": price_cap,
        "sample_size": N_SAMPLE,
        "train_fraction": TRAIN_FRACTION,
        "standardization": "separate_train_and_test_population_sd",
        "standardization_reduction_dtype": "float64",
        "minimum_clickout_alternatives_after_filtering": MIN_CLICKOUT_ALTERNATIVES,
        "position_bins": {
            "count": POSITION_BIN_COUNT,
            "width": 5,
            "emitted_columns": [
                f"position_bin_{index}" for index in range(POSITION_BIN_COUNT)
            ],
        },
        "platform_filter_diagnostics": {},
        "outputs": {},
    }
    outputs = manifest["outputs"]
    platform_diagnostics = manifest["platform_filter_diagnostics"]
    assert isinstance(outputs, dict)
    assert isinstance(platform_diagnostics, dict)
    for platform in PLATFORMS:
        frame, columns, diagnostics = prepare_platform(prep_dir, platform, price_cap)
        platform_diagnostics[platform] = diagnostics
        if len(columns) != 23:
            raise AssertionError(
                f"Trivago matrix schema must contain 23 columns, got {len(columns)}."
            )
        for trial in TRIALS:
            train, test = split(frame, trial)
            train_scaler = fit_scaler(train)
            test_scaler = fit_scaler(test)
            train = add_outside(apply_scaler(train, train_scaler), columns)
            test = add_outside(apply_scaler(test, test_scaler), columns)
            train_array = np.ascontiguousarray(train[columns].to_numpy(np.float64))
            test_array = np.ascontiguousarray(test[columns].to_numpy(np.float64))
            name = f"10k_sample_{platform}_{trial}_p2000.mat"
            output_path = output_dir / name
            savemat(
                output_path,
                {"data_train": train_array, "data_test": test_array},
                do_compression=True,
            )
            stabilize_mat_header(output_path)
            outputs[name] = {
                "train_shape": list(train_array.shape),
                "test_shape": list(test_array.shape),
                "columns": columns,
                "scaler": {"train": train_scaler, "test": test_scaler},
            }
            print(f"{name}: train={train_array.shape}, test={test_array.shape}")
    (output_dir / "manifest.json").write_text(
        json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--prep-dir", required=True, type=Path)
    parser.add_argument("--output-dir", required=True, type=Path)
    parser.add_argument("--price-cap", type=float, default=2000.0)
    args = parser.parse_args()
    build(args.prep_dir.resolve(), args.output_dir.resolve(), args.price_cap)


if __name__ == "__main__":
    main()
